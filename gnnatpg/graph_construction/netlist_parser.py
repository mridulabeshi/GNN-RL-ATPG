"""
netlist_parser.py - Gate-Level Netlist Parser

Parses Yosys-generated gate-level Verilog netlists into structured
intermediate representations for graph construction.
"""

import re
import logging
from dataclasses import dataclass, field
from typing import Optional
from pathlib import Path
from enum import Enum, auto

logger = logging.getLogger(__name__)


class GateType(Enum):
    """Supported gate types mapped from Yosys cell names."""

    AND2 = auto()
    AND3 = auto()
    AND4 = auto()

    OR2 = auto()
    OR3 = auto()
    OR4 = auto()

    NAND2 = auto()
    NAND3 = auto()
    NAND4 = auto()

    NOR2 = auto()
    NOR3 = auto()
    NOR4 = auto()

    XOR2 = auto()
    XNOR2 = auto()

    NOT = auto()
    BUF = auto()

    MUX2 = auto()

    DFF = auto()
    DFFE = auto()

    UNKNOWN = auto()

    @classmethod
    def from_yosys_name(cls, name: str) -> "GateType":
        """Map a Yosys cell name to a GateType."""

        name_upper = name.upper().strip()

        # Yosys internal sequential cells
        if "DFFE" in name_upper:
            return cls.DFFE

        if "DFF" in name_upper:
            return cls.DFF

        # Multiplexers
        if "MUX" in name_upper:
            return cls.MUX2

        # AND gates
        if "AND" in name_upper and "NAND" not in name_upper:
            return cls.AND2

        # NAND gates
        if "NAND" in name_upper:
            return cls.NAND2

        # NOR gates
        if "NOR" in name_upper:
            return cls.NOR2

        # OR gates
        if "OR" in name_upper and "NOR" not in name_upper:
            return cls.OR2

        # XNOR must be checked before XOR
        if "XNOR" in name_upper:
            return cls.XNOR2

        if "XOR" in name_upper:
            return cls.XOR2

        # NOT / inverter
        if "NOT" in name_upper:
            return cls.NOT

        # Buffer
        if "BUF" in name_upper:
            return cls.BUF

        return cls.UNKNOWN


@dataclass
class Port:
    """Represents a module port."""

    name: str
    direction: str  # input, output, inout
    bus_low: Optional[int] = None
    bus_high: Optional[int] = None

    @property
    def is_bus(self) -> bool:
        return self.bus_low is not None and self.bus_high is not None

    @property
    def width(self) -> int:
        if not self.is_bus:
            return 1

        return abs(self.bus_high - self.bus_low) + 1


@dataclass
class Gate:
    """Represents a logic gate instance in the netlist."""

    gate_id: int
    instance_name: str
    gate_type: GateType
    cell_type: str

    input_nets: list[str] = field(default_factory=list)
    output_net: str = ""

    attributes: dict = field(default_factory=dict)


@dataclass
class Wire:
    """Represents a wire/net in the netlist."""

    name: str
    width: int = 1

    is_input: bool = False
    is_output: bool = False

    driven_by: Optional[int] = None
    fanout_gate_ids: list[int] = field(default_factory=list)


@dataclass
class Netlist:
    """Complete parsed netlist."""

    module_name: str

    ports: list[Port] = field(default_factory=list)
    gates: list[Gate] = field(default_factory=list)

    wires: dict[str, Wire] = field(default_factory=dict)

    primary_inputs: list[str] = field(default_factory=list)
    primary_outputs: list[str] = field(default_factory=list)

    flip_flops: list[int] = field(default_factory=list)

    @property
    def num_gates(self) -> int:
        return len(self.gates)

    @property
    def num_wires(self) -> int:
        return len(self.wires)

    @property
    def num_inputs(self) -> int:
        return len(self.primary_inputs)

    @property
    def num_outputs(self) -> int:
        return len(self.primary_outputs)

    @property
    def num_ffs(self) -> int:
        return len(self.flip_flops)

    def stats(self) -> dict:
        gate_type_counts = {}

        for gate in self.gates:
            gate_type = gate.gate_type.name
            gate_type_counts[gate_type] = (
                gate_type_counts.get(gate_type, 0) + 1
            )

        return {
            "module_name": self.module_name,
            "num_gates": self.num_gates,
            "num_wires": self.num_wires,
            "num_inputs": self.num_inputs,
            "num_outputs": self.num_outputs,
            "num_flip_flops": self.num_ffs,
            "gate_type_counts": gate_type_counts,
        }


class NetlistParser:
    """
    Parses gate-level Verilog netlists generated by Yosys.

    Handles:
        - Module declarations
        - Input/output/wire declarations
        - Yosys internal cell names such as $_AND_
        - Cell instance names containing $
        - Pin-to-net connectivity
        - Primary inputs and outputs
        - Flip-flop detection
    """

    # ------------------------------------------------------------------
    # Regex patterns
    # ------------------------------------------------------------------

    RE_MODULE_START = re.compile(
        r"\bmodule\s+([A-Za-z_][A-Za-z0-9_$]*)\s*\((.*?)\)\s*;",
        re.DOTALL,
    )

    RE_MODULE_END = re.compile(r"\bendmodule\b")

    RE_INPUT = re.compile(
        r"\binput\s+"
        r"(?:\[(\d+):(\d+)\]\s+)?"
        r"([^;]+);"
    )

    RE_OUTPUT = re.compile(
        r"\boutput\s+"
        r"(?:\[(\d+):(\d+)\]\s+)?"
        r"([^;]+);"
    )

    RE_INOUT = re.compile(
        r"\binout\s+"
        r"(?:\[(\d+):(\d+)\]\s+)?"
        r"([^;]+);"
    )

    RE_WIRE = re.compile(
        r"\bwire\s+"
        r"(?:\[(\d+):(\d+)\]\s+)?"
        r"([^;]+);"
    )

    # IMPORTANT:
    # Yosys names contain '$', e.g.
    # $_AND_
    # $_MUX_
    # $_DFF_P_
    # _123_
    #
    # Therefore \w+ is NOT sufficient.
    IDENTIFIER = r"[A-Za-z_$][A-Za-z0-9_$]*"

    RE_GATE_INST = re.compile(
        rf"({IDENTIFIER})\s+({IDENTIFIER})\s*\((.*?)\)\s*;",
        re.DOTALL,
    )

    # Pin names and net names may contain '$', '[', ']', etc.
    RE_PIN_MAP = re.compile(
        r"\.([A-Za-z_][A-Za-z0-9_$]*)\s*"
        r"\(\s*"
        r"([^()\s,]+)"
        r"\s*\)"
    )

    RE_ATTRIBUTE = re.compile(
        r"/\*\s*(.*?)\s*\*/"
    )

    def __init__(self):
        self._gate_counter = 0

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def parse_file(self, netlist_path: str | Path) -> Netlist:
        """Parse a Verilog netlist file."""

        path = Path(netlist_path)

        if not path.exists():
            raise FileNotFoundError(
                f"Netlist not found: {path}"
            )

        content = path.read_text()

        return self.parse_string(content)

    def parse_string(self, content: str) -> Netlist:
        """Parse Verilog netlist from a string."""

        self._gate_counter = 0

        # --------------------------------------------------------------
        # Find module
        # --------------------------------------------------------------

        module_match = self.RE_MODULE_START.search(content)

        if not module_match:
            raise ValueError(
                "No module found in netlist"
            )

        module_name = module_match.group(1)

        netlist = Netlist(
            module_name=module_name
        )

        # --------------------------------------------------------------
        # Remove comments while preserving structure
        # --------------------------------------------------------------

        content_no_comments = re.sub(
            r"/\*.*?\*/",
            "",
            content,
            flags=re.DOTALL,
        )

        content_no_comments = re.sub(
            r"//.*",
            "",
            content_no_comments,
        )

        # --------------------------------------------------------------
        # Extract module body
        # --------------------------------------------------------------

        module_match = self.RE_MODULE_START.search(
            content_no_comments
        )

        if not module_match:
            raise ValueError(
                "Unable to parse module declaration"
            )

        module_start = module_match.end()

        end_match = self.RE_MODULE_END.search(
            content_no_comments,
            module_start,
        )

        if end_match:
            module_body = content_no_comments[
                module_start:end_match.start()
            ]
        else:
            module_body = content_no_comments[
                module_start:
            ]

        # --------------------------------------------------------------
        # Parse declarations
        # --------------------------------------------------------------

        self._parse_all_declarations(
            module_body,
            netlist,
        )

        # --------------------------------------------------------------
        # Parse gate/cell instantiations
        # --------------------------------------------------------------

        self._parse_all_gates(
            module_body,
            netlist,
        )

        # --------------------------------------------------------------
        # Build connectivity
        # --------------------------------------------------------------

        self._build_connectivity(
            netlist
        )

        # --------------------------------------------------------------
        # Identify primary ports
        # --------------------------------------------------------------

        self._identify_primary_ports(
            netlist
        )

        logger.info(
            f"Parsed '{module_name}': "
            f"{netlist.num_gates} gates, "
            f"{netlist.num_wires} wires, "
            f"{netlist.num_inputs} inputs, "
            f"{netlist.num_outputs} outputs, "
            f"{netlist.num_ffs} flip-flops"
        )

        return netlist

    # ------------------------------------------------------------------
    # Declaration parsing
    # ------------------------------------------------------------------

    def _parse_all_declarations(
        self,
        content: str,
        netlist: Netlist,
    ):
        """Parse all input, output, inout and wire declarations."""

        # Inputs
        for match in self.RE_INPUT.finditer(content):

            bus_high = match.group(1)
            bus_low = match.group(2)
            names = match.group(3)

            self._add_ports(
                names,
                "input",
                bus_high,
                bus_low,
                netlist,
            )

        # Outputs
        for match in self.RE_OUTPUT.finditer(content):

            bus_high = match.group(1)
            bus_low = match.group(2)
            names = match.group(3)

            self._add_ports(
                names,
                "output",
                bus_high,
                bus_low,
                netlist,
            )

        # Inouts
        for match in self.RE_INOUT.finditer(content):

            bus_high = match.group(1)
            bus_low = match.group(2)
            names = match.group(3)

            self._add_ports(
                names,
                "inout",
                bus_high,
                bus_low,
                netlist,
            )

        # Wires
        for match in self.RE_WIRE.finditer(content):

            bus_high = match.group(1)
            bus_low = match.group(2)
            names = match.group(3)

            width = 1

            if bus_high and bus_low:
                width = (
                    abs(
                        int(bus_high)
                        - int(bus_low)
                    )
                    + 1
                )

            # Remove commas and whitespace
            names = names.strip()

            for name in names.split(","):

                name = name.strip()

                if not name:
                    continue

                # Remove trailing declaration artifacts
                name = name.strip(";")

                if name not in netlist.wires:
                    netlist.wires[name] = Wire(
                        name=name,
                        width=width,
                    )

    def _add_ports(
        self,
        names: str,
        direction: str,
        bus_high: Optional[str],
        bus_low: Optional[str],
        netlist: Netlist,
    ):
        """Add ports to the netlist."""

        width = 1

        if bus_high and bus_low:
            width = (
                abs(
                    int(bus_high)
                    - int(bus_low)
                )
                + 1
            )

        for name in names.split(","):

            name = name.strip()

            if not name:
                continue

            # Remove trailing semicolon
            name = name.strip(";")

            port = Port(
                name=name,
                direction=direction,
                bus_low=(
                    int(bus_low)
                    if bus_low
                    else None
                ),
                bus_high=(
                    int(bus_high)
                    if bus_high
                    else None
                ),
            )

            netlist.ports.append(port)

            if direction == "input":
                netlist.primary_inputs.append(
                    name
                )

            elif direction == "output":
                netlist.primary_outputs.append(
                    name
                )

            if name not in netlist.wires:

                netlist.wires[name] = Wire(
                    name=name,
                    width=width,
                    is_input=direction == "input",
                    is_output=direction == "output",
                )

            else:

                netlist.wires[name].is_input = (
                    netlist.wires[name].is_input
                    or direction == "input"
                )

                netlist.wires[name].is_output = (
                    netlist.wires[name].is_output
                    or direction == "output"
                )

    # ------------------------------------------------------------------
    # Gate parsing
    # ------------------------------------------------------------------

    def _parse_all_gates(
        self,
        content: str,
        netlist: Netlist,
    ):
        """Parse all Yosys cell instantiations."""

        for match in self.RE_GATE_INST.finditer(
            content
        ):

            cell_type = match.group(1)
            instance_name = match.group(2)
            pin_connections = match.group(3)

            # Skip Verilog keywords
            if cell_type in {
                "module",
                "endmodule",
                "input",
                "output",
                "inout",
                "wire",
                "reg",
                "logic",
                "assign",
            }:
                continue

            # ----------------------------------------------------------
            # Only accept things that look like Yosys cells
            # ----------------------------------------------------------

            gate_type = GateType.from_yosys_name(
                cell_type
            )

            if gate_type == GateType.UNKNOWN:

                # Ignore non-gate constructs
                # rather than adding them as gates.
                continue

            # ----------------------------------------------------------
            # Parse pin connections
            # ----------------------------------------------------------

            input_nets = []
            output_net = ""

            for pin_match in self.RE_PIN_MAP.finditer(
                pin_connections
            ):

                pin_name = pin_match.group(1)
                net_name = pin_match.group(2)

                pin_upper = pin_name.upper()

                # Common Yosys output pins
                if pin_upper in {
                    "Y",
                    "Q",
                    "QN",
                    "O",
                    "OUT",
                }:

                    if not output_net:
                        output_net = net_name

                else:
                    input_nets.append(
                        net_name
                    )

            # ----------------------------------------------------------
            # Some cells have no recognizable output.
            # Still preserve them, but don't invent a net.
            # ----------------------------------------------------------

            self._gate_counter += 1

            gate = Gate(
                gate_id=self._gate_counter,
                instance_name=instance_name,
                gate_type=gate_type,
                cell_type=cell_type,
                input_nets=input_nets,
                output_net=output_net,
            )

            netlist.gates.append(
                gate
            )

            # Track flip-flops
            if gate.gate_type in (
                GateType.DFF,
                GateType.DFFE,
            ):

                netlist.flip_flops.append(
                    gate.gate_id
                )

    # ------------------------------------------------------------------
    # Connectivity
    # ------------------------------------------------------------------

    def _build_connectivity(
        self,
        netlist: Netlist,
    ):
        """Build wire-to-gate connectivity."""

        for gate in netlist.gates:

            # ----------------------------------------------------------
            # Output wire
            # ----------------------------------------------------------

            if (
                gate.output_net
                and gate.output_net
                not in netlist.wires
            ):

                netlist.wires[
                    gate.output_net
                ] = Wire(
                    name=gate.output_net
                )

            if (
                gate.output_net
                and gate.output_net
                in netlist.wires
            ):

                netlist.wires[
                    gate.output_net
                ].driven_by = gate.gate_id

            # ----------------------------------------------------------
            # Input wires
            # ----------------------------------------------------------

            for net in gate.input_nets:

                if net not in netlist.wires:

                    netlist.wires[net] = Wire(
                        name=net
                    )

                if (
                    gate.gate_id
                    not in netlist.wires[
                        net
                    ].fanout_gate_ids
                ):

                    netlist.wires[
                        net
                    ].fanout_gate_ids.append(
                        gate.gate_id
                    )

    # ------------------------------------------------------------------
    # Primary ports
    # ------------------------------------------------------------------

    def _identify_primary_ports(
        self,
        netlist: Netlist,
    ):
        """Mark primary inputs and outputs on wires."""

        for name in netlist.primary_inputs:

            if name in netlist.wires:

                netlist.wires[
                    name
                ].is_input = True

        for name in netlist.primary_outputs:

            if name in netlist.wires:

                netlist.wires[
                    name
                ].is_output = True


# ----------------------------------------------------------------------
# Convenience function
# ----------------------------------------------------------------------

def parse_netlist(
    netlist_path: str | Path,
) -> Netlist:
    """
    Convenience function for parsing a netlist.

    Example:
        netlist = parse_netlist(
            "data/netlists/picorv32.v"
        )
    """

    parser = NetlistParser()

    return parser.parse_file(
        netlist_path
    )